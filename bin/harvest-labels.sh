#!/usr/bin/env bash
# Harvest eval labels from GitHub for the auto PR reviewer.
#
# A thumbs-up/down footer produced no reactions to learn from, so labels come
# from behavior instead (what CodeRabbit, Cursor and Greptile measure):
#   bug  = a human replied "fixed/confirmed/good catch/..." in the thread, or the
#          flagged line changed later (thread outdated) and the PR was merged
#   fp   = a human replied "false positive/dismiss/intentional/pre-existing/..."
#
# Writes:
#   ~/.config/auto-pr-review/eval/labels.tsv       (manual rows above the marker are kept)
#   ~/.config/auto-pr-review/eval/dismissals.md    (fp threads, for curating repos/*.md)
#   ~/.config/auto-pr-review/eval/harvest-summary.txt
#
# Read-only against GitHub. Reply text is PR-author-controlled: it is only ever
# matched against fixed regexes and written to files for a human to read, never
# fed into a prompt.

set -euo pipefail

CONF_DIR="${HOME}/.config/auto-pr-review"
EVAL_DIR="${CONF_DIR}/eval"
LABELS="${EVAL_DIR}/labels.tsv"
DISMISSALS="${EVAL_DIR}/dismissals.md"
SUMMARY="${EVAL_DIR}/harvest-summary.txt"
USAGE_DB="${HOME}/.local/state/auto-pr-review/usage.db"
MARKER="# --- generated by harvest-labels.sh (everything below is overwritten on each run) ---"
mkdir -p "$EVAL_DIR"

ME=$(gh api user --jq .login)

Q='query($owner:String!,$name:String!,$num:Int!){ repository(owner:$owner,name:$name){ pullRequest(number:$num){
  number merged state
  reviews(first:100){ nodes{ databaseId author{login} body } }
  reviewThreads(first:100){ nodes{ isResolved isOutdated
    comments(first:30){ nodes{ databaseId author{login} body path line originalLine outdated pullRequestReview{ databaseId } } } } } } } }'

# jq: one TSV row per bot inline comment that can be labeled:
#   repo pr sha kind path line note
JQ_ROWS='
  .data.repository.pullRequest as $pr
  | ($pr.reviews.nodes | map(select(.author.login == $me and (.body // "" | test("claude-pr-reviewer"))))
     | map({key: (.databaseId|tostring), value: ((.body // "") | capture("head_sha=(?<sha>[0-9a-f]{40})").sha)}) | from_entries) as $sha_of
  | $pr.reviewThreads.nodes[]
  | .comments.nodes as $cs
  | select(($cs | length) > 0 and $cs[0].author.login == $me and ($cs[0].body // "" | test("^\\*\\*\\[")))
  | $cs[0] as $bot
  | ($sha_of[($bot.pullRequestReview.databaseId // 0 | tostring)] // "") as $sha
  | select($sha != "")
  | [ $cs[1:][] | select(.author.login != $me) ] as $replies
  | ($replies | map(.body // "") | join(" ") | gsub("\\s+"; " ")) as $rtext
  # Precedence: an explicit dismissal wins; then an explicit fix confirmation;
  # weak "intentional/pre-existing" wording only counts when nothing was fixed
  # (replies like "Fixed in X. Left the pre-existing ones alone" are bugs).
  | (if ($rtext | test("false.?positive|dismiss(ing|ed)?|not a bug|not an issue|working as intended|won.?t fix"; "i")) then "fp"
     elif ($rtext | test("fixed|confirmed|good catch|addressed|you.?re right|resolved in|done in"; "i")) then "bug"
     elif ($rtext | test("intentional|by design|pre-?existing|out of scope"; "i")) then "fp"
     elif (.isOutdated and $pr.merged and ($replies | length) == 0) then "bug"
     else "" end) as $kind
  | select($kind != "")
  | (if ($replies | length) > 0 then ("reply: " + ($rtext | .[0:140])) else "line changed before merge (no reply)" end) as $note
  | [$repo, ($pr.number|tostring), $sha, $kind, $bot.path, (($bot.originalLine // $bot.line // 1)|tostring), $note] | @tsv'

# fp threads in full, for a human to turn into repos/<repo>.md "known false positives".
JQ_DISMISSALS='
  .data.repository.pullRequest as $pr
  | $pr.reviewThreads.nodes[]
  | .comments.nodes as $cs
  | select(($cs | length) > 1 and $cs[0].author.login == $me and ($cs[0].body // "" | test("^\\*\\*\\[")))
  | ([ $cs[1:][] | select(.author.login != $me) | .body // "" ] | join(" ") | gsub("\\s+"; " ")) as $rtext
  | select(($rtext | test("false.?positive|dismiss(ing|ed)?|not a bug|not an issue|working as intended|won.?t fix"; "i"))
           or (($rtext | test("intentional|by design|pre-?existing|out of scope"; "i"))
               and ($rtext | test("fixed|confirmed|good catch|addressed|you.?re right|resolved in|done in"; "i") | not)))
  | "### \($repo)#\($pr.number) \($cs[0].path):\($cs[0].originalLine // $cs[0].line)\n\n**Finding:** \($cs[0].body | gsub("\\s+"; " ") | .[0:400])\n\n**Team reply:** \($rtext | .[0:400])\n"'

ROWS=$(mktemp -t harvest-rows.XXXXXX); DIS=$(mktemp -t harvest-dis.XXXXXX)
trap 'rm -f "$ROWS" "$DIS"' EXIT

n_prs=0; n_fail=0
while IFS='|' read -r repo pr; do
  owner=${repo%/*}; name=${repo#*/}
  if ! json=$(gh api graphql -f query="$Q" -f owner="$owner" -f name="$name" -F num="$pr" 2>/dev/null); then
    n_fail=$((n_fail+1)); continue
  fi
  n_prs=$((n_prs+1))
  jq -r --arg me "$ME" --arg repo "$repo" "$JQ_ROWS" <<<"$json" >> "$ROWS" || true
  jq -r --arg me "$ME" --arg repo "$repo" "$JQ_DISMISSALS" <<<"$json" >> "$DIS" || true
done < <(sqlite3 "$USAGE_DB" "SELECT DISTINCT repo, pr FROM posts ORDER BY repo, pr;")

# labels.tsv: keep the header/manual section, replace the generated block.
if [[ -f "$LABELS" ]] && grep -qF "$MARKER" "$LABELS"; then
  head=$(sed "/^${MARKER//\//\\/}\$/,\$d" "$LABELS")
elif [[ -f "$LABELS" ]]; then
  head=$(cat "$LABELS")
else
  head="# Eval labels. Columns: repo <TAB> pr <TAB> sha <TAB> kind(bug|fp) <TAB> path <TAB> line <TAB> note"
fi
{
  printf '%s\n' "$head"
  printf '%s\n' "$MARKER"
  printf '# harvested %s from %d PRs with bot reviews (%d fetch failures)\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$n_prs" "$n_fail"
  sort -u "$ROWS"
} > "$LABELS"

{
  printf '# Dismissed findings (team said false positive / intentional)\n\n'
  printf 'Harvested %s. Curate the recurring ones into repos/<repo>.md under "Do NOT flag".\n\n' "$(date -u +%Y-%m-%d)"
  cat "$DIS"
} > "$DISMISSALS"

n_bug=$(awk -F'\t' '$4=="bug"' "$ROWS" | sort -u | wc -l | tr -d ' ')
n_fp=$(awk -F'\t' '$4=="fp"' "$ROWS" | sort -u | wc -l | tr -d ' ')
n_reply=$(grep -c $'\treply: ' "$ROWS" || true)
{
  printf 'harvested_at\t%s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  printf 'prs_scanned\t%d\nfetch_failures\t%d\n' "$n_prs" "$n_fail"
  printf 'labels_bug\t%d\nlabels_fp\t%d\nlabels_from_replies\t%d\n' "$n_bug" "$n_fp" "$n_reply"
} > "$SUMMARY"

echo "PRs scanned: $n_prs (fetch failures: $n_fail)"
echo "labels: bug=$n_bug fp=$n_fp (from replies: $n_reply)"
echo "wrote $LABELS"
echo "wrote $DISMISSALS"
